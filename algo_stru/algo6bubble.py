# 버블 정렬은 인접한 두 개의 원소를 비교하여 자리를 교환하는 단순한 형태의 정렬 알고리즘 

# 동작 방식
# 인접 원소 비교: 배열의 첫 번째 원소부터 시작해 바로 옆의 원소와 값을 비교.
# 자리 교환: 순서가 잘못되어 있다면 (예:오름차순인데 앞의 값이 뒤의 값보다 크면) 
#           두 원소의 위치를 서로 바꿉니다.
# 1회전 완료: 이 과정을 끝까지 반복하면, 가장 큰 원소(오름차순 기준)가 배열의 
#            맨 마지막 자리로 이동.
# 범위 축소: 맨 마지막으로 이동한 원소는 정렬이 완료된 것으로 간주하고 다음 회전에서는 제외. 
#           전체 원소 수만큼 회전을 반복.

# 이웃한 요소와 비교
# [2 4 5 1 3]
# [2 4 5 1 3]
# [2 4 1 5 3]
# [2 4 1 3 5]
# ...

def bubble_sort(a):
    n = len(a)
    while True:
        change = False   # flag (자료 앞뒤 변경 여부)

        for i in range(0, n - 1):
            if a[i] > a[i + 1]:   # 앞이 뒤보다 크면
                print(a)
                a[i], a[i + 1] = a[i + 1], a[i]
                change = True   # 교환이 발생함

        if change == False:
            return

d = [2, 4, 5, 1, 3]
bubble_sort(d)
print()
print(d)
